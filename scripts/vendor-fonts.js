// Copies the shipped UI fonts (SIL Open Font License) from node_modules into vendor/fonts and writes
// src/ui/fonts.css. The game makes no external font request: everything is served from vendor/fonts.
import { copyFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';

const FONTS = [
  { pkg: 'atkinson-hyperlegible', family: 'Atkinson Hyperlegible', weights: [400, 700] },
  { pkg: 'barlow-condensed', family: 'Barlow Condensed', weights: [600, 700] },
  { pkg: 'orbitron', family: 'Orbitron', weights: [600, 700] },
  { pkg: 'chakra-petch', family: 'Chakra Petch', weights: [600, 700] },
  { pkg: 'silkscreen', family: 'Silkscreen', weights: [400, 700] },
  { pkg: 'im-fell-dw-pica', family: 'IM Fell DW Pica', weights: [400] },
];
mkdirSync('vendor/fonts', { recursive: true });
let css = '/* generated by scripts/vendor-fonts.js: self-hosted fonts, no external requests */\n';
let lic = 'The fonts in this folder are licensed under the SIL Open Font License 1.1 (see each package license).\n';
for (const f of FONTS) {
  for (const w of f.weights) {
    const name = `${f.pkg}-latin-${w}-normal.woff2`;
    const src = `node_modules/@fontsource/${f.pkg}/files/${name}`;
    if (!existsSync(src)) throw new Error('missing ' + src);
    copyFileSync(src, `vendor/fonts/${name}`);
    css += `@font-face { font-family: "${f.family}"; font-style: normal; font-weight: ${w}; font-display: swap; src: url("../../vendor/fonts/${name}") format("woff2"); }\n`;
  }
  lic += `- ${f.family}\n`;
  if (existsSync(`node_modules/@fontsource/${f.pkg}/LICENSE`)) copyFileSync(`node_modules/@fontsource/${f.pkg}/LICENSE`, `vendor/fonts/LICENSE-${f.pkg}.txt`);
}
writeFileSync('vendor/fonts/README.txt', lic);
writeFileSync('src/ui/fonts.css', css);
console.log(`vendored ${FONTS.length} font families -> vendor/fonts/, wrote src/ui/fonts.css`);
